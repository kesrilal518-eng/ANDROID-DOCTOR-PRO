package com.androiddoctor.pro.utils

import android.content.Context
import com.androiddoctor.pro.data.DeviceInfo
import com.androiddoctor.pro.data.DiagnosticResult
import com.androiddoctor.pro.data.TestStatus
import com.tom_roush.pdfbox.android.PDFBoxResourceLoader
import com.tom_roush.pdfbox.pdmodel.PDDocument
import com.tom_roush.pdfbox.pdmodel.PDPage
import com.tom_roush.pdfbox.pdmodel.PDPageContentStream
import com.tom_roush.pdfbox.pdmodel.common.PDRectangle
import com.tom_roush.pdfbox.pdmodel.font.PDType1Font
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object PdfReportGenerator {

    fun generate(
        context: Context,
        deviceInfo: DeviceInfo,
        results: List<DiagnosticResult>,
        overallScore: Int
    ): File {
        PDFBoxResourceLoader.init(context)
        val dir = File(context.cacheDir, "reports").apply { mkdirs() }
        val stamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US).format(Date())
        val file = File(dir, "AndroidDoctorPro_Report_$stamp.pdf")

        PDDocument().use { doc ->
            var page = PDPage(PDRectangle.A4)
            doc.addPage(page)
            var cs = PDPageContentStream(doc, page)
            var y = 800f
            val margin = 40f

            fun newPageIfNeeded(needed: Float = 60f) {
                if (y < needed) {
                    cs.close()
                    page = PDPage(PDRectangle.A4)
                    doc.addPage(page)
                    cs = PDPageContentStream(doc, page)
                    y = 800f
                }
            }

            fun writeLine(text: String, font: PDType1Font = PDType1Font.HELVETICA, size: Float = 11f) {
                newPageIfNeeded()
                cs.beginText()
                cs.setFont(font, size)
                cs.newLineAtOffset(margin, y)
                cs.showText(text.take(90))
                cs.endText()
                y -= size + 6f
            }

            writeLine("ANDROID DOCTOR PRO - Diagnostic Report", PDType1Font.HELVETICA_BOLD, 16f)
            writeLine("Generated: ${SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.getDefault()).format(Date())}")
            writeLine("Overall Health Score: $overallScore / 100", PDType1Font.HELVETICA_BOLD, 13f)
            y -= 10f

            writeLine("DEVICE INFORMATION", PDType1Font.HELVETICA_BOLD, 13f)
            writeLine("Manufacturer: ${deviceInfo.manufacturer} | Brand: ${deviceInfo.brand}")
            writeLine("Model: ${deviceInfo.model} (${deviceInfo.device})")
            writeLine("Android: ${deviceInfo.androidVersion} (SDK ${deviceInfo.sdkInt}) | Patch: ${deviceInfo.securityPatch}")
            writeLine("RAM: ${deviceInfo.availableRamMb} / ${deviceInfo.totalRamMb} MB free")
            writeLine("Storage: ${"%.2f".format(deviceInfo.availableStorageGb)} / ${"%.2f".format(deviceInfo.totalStorageGb)} GB free")
            writeLine("Display: ${deviceInfo.screenWidthPx}x${deviceInfo.screenHeightPx} @ ${deviceInfo.refreshRateHz}Hz")
            writeLine("Battery: ${deviceInfo.batteryLevel}% | ${deviceInfo.batteryTemperatureC}°C | ${deviceInfo.batteryHealth}")
            y -= 12f

            writeLine("DIAGNOSTIC RESULTS", PDType1Font.HELVETICA_BOLD, 13f)
            results.forEach { r ->
                newPageIfNeeded(80f)
                writeLine("[${r.status.name}] ${r.name}", PDType1Font.HELVETICA_BOLD, 11f)
                writeLine(r.message)
                if (r.recommendation.isNotBlank()) {
                    writeLine("Advice: ${r.recommendation}")
                }
                y -= 6f
            }

            y -= 10f
            writeLine("DISCLAIMER", PDType1Font.HELVETICA_BOLD, 11f)
            writeLine("This report is generated by software diagnostics only.")
            writeLine("It cannot detect motherboard, IC-level, or physical hardware faults with certainty.")
            writeLine("Always seek professional hardware inspection for persistent issues.")
            writeLine("ANDROID DOCTOR PRO does not require or use root access.")

            cs.close()
            doc.save(file)
        }
        return file
    }
}
